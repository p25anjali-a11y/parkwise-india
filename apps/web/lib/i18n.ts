export const DICTS: Record<Lang, Dict> = { en, hi, gu, mr };

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const s = DICTS[lang][key] ?? en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? "")) : s;
}

/** Maps the English labels produced by the pricing and availability code to dictionary keys. */
const LABEL_KEYS: Record<string, string> = {
  "Likely space": "likelySpace",
  Tight: "tight",
  "Nearly full": "nearlyFull",
  "No live availability": "noLive",
  "off-peak": "offPeak",
  standard: "standard",
  busy: "busy",
  peak: "peak",
};
export function translateLabel(lang: Lang, label: string): string {
  const k = LABEL_KEYS[label] ?? LABEL_KEYS[label.toLowerCase()];
  return k ? translate(lang, k) : label;
}
